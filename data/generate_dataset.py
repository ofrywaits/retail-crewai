# ========================================
# פונקציה ראשית לייצור נתונים
# ========================================

def generate_israeli_retail(n_rows=10000):
    rows = []

    start_date = datetime(2022, 1, 1)
    end_date   = datetime(2024, 12, 31)
    date_range = (end_date - start_date).days

    order_id = 1001

    while len(rows) < n_rows:
        # תאריך אקראי
        date = start_date + timedelta(days=random.randint(0, date_range))

        # בדיקת יום שבת (6 = שבת)
        day_of_week = date.weekday()
        hebrew_days = ["שני", "שלישי", "רביעי", "חמישי", "שישי", "שבת", "ראשון"]
        day_name = hebrew_days[day_of_week]

        # שבת = 80% ירידה במכירות
        if day_of_week == 5:
            if random.random() < 0.8:
                continue

        # בדיקת חג
        holiday_key  = (date.month, date.day)
        holiday_name = ""
        holiday_mult = 1.0
        if holiday_key in HOLIDAYS:
            holiday_name, holiday_mult = HOLIDAYS[holiday_key]
            # ביום כיפור רוב החנויות סגורות
            if holiday_name == "יום כיפור" and random.random() < 0.9:
                continue

        # בחירת עיר ושרשת
        city  = random.choice(list(CITIES_REGIONS.keys()))
        region = CITIES_REGIONS[city]
        chain = random.choice(CHAINS)

        # בחירת קטגוריה ומוצר
        category = random.choice(list(CATEGORIES.keys()))
        cat_data = CATEGORIES[category]
        sub_cat  = random.choice(cat_data["תת-קטגוריות"])

        if sub_cat in cat_data["מוצרים"]:
            product, base_price = random.choice(cat_data["מוצרים"][sub_cat])
        else:
            continue

        # כמות ומחיר
        quantity   = random.randint(1, 8)
        discount   = random.choice([0, 0, 0, 0.05, 0.10, 0.15, 0.20])
        unit_price = round(base_price * (1 - discount) * holiday_mult, 2)
        sales      = round(unit_price * quantity, 2)
        profit_pct = cat_data["רווחיות"] + np.random.normal(0, 0.03)
        profit     = round(sales * profit_pct, 2)

        # פרמטר עונתי — קיץ: יותר משקאות/פירות, חורף: יותר חימום
        season_map = {1: "חורף", 2: "חורף", 3: "אביב", 4: "אביב",
                      5: "אביב", 6: "קיץ",  7: "קיץ",  8: "קיץ",
                      9: "סתיו", 10: "סתיו", 11: "חורף", 12: "חורף"}
        season = season_map[date.month]

        rows.append({
            "מספר_הזמנה":    f"IL-{order_id:05d}",
            "תאריך":          date.strftime("%Y-%m-%d"),
            "שנה":             date.year,
            "חודש":            date.month,
            "יום_בשבוע":      day_name,
            "עונה":            season,
            "חג":              holiday_name,
            "רשת":             chain,
            "עיר":             city,
            "אזור":            region,
            "קטגוריה":        category,
            "תת_קטגוריה":     sub_cat,
            "מוצר":            product,
            "כמות":            quantity,
            "מחיר_יחידה":     unit_price,
            "הנחה_אחוז":      discount,
            "מכירות_ש":       sales,
            "רווח_ש":         profit,
            "אחוז_רווח":      round(profit / sales * 100, 1) if sales > 0 else 0,
        })

        order_id += 1

    return pd.DataFrame(rows[:n_rows])


